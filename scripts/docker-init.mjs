#!/usr/bin/env node
/**
 * Generate a secure .env configuration for Docker Compose deployments.
 *
 * Modes:
 *   --local-eval          Configure localhost evaluation on http://127.0.0.1:3005 (or http://localhost:3005)
 *   --url <origin>        Configure internet-accessible production deployment (e.g. https://notes.example.com)
 *   --force               Overwrite an existing .env file
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function buildDockerEnvContent({
  localEval = false,
  url,
  port = 3005,
  bindHost = '127.0.0.1',
  existing = {},
} = {}) {
  const normalizedPort = Number(port) || 3005;
  const authUrl = localEval
    ? url || `http://localhost:${normalizedPort}`
    : url || existing.BETTER_AUTH_URL || '';

  if (localEval) {
    let parsed;
    try {
      parsed = new URL(authUrl);
    } catch {
      throw new Error(`Invalid URL "${authUrl}" for --local-eval.`);
    }
    if (parsed.hostname !== 'localhost' && parsed.hostname !== '127.0.0.1') {
      throw new Error(
        `--local-eval requires a localhost or 127.0.0.1 BETTER_AUTH_URL, got "${authUrl}".`,
      );
    }
    if (bindHost !== '127.0.0.1' && bindHost !== '::1' && bindHost !== 'localhost') {
      throw new Error(`--local-eval requires a loopback bind host, got "${bindHost}".`);
    }
  } else {
    if (!authUrl) {
      throw new Error(
        'Production Docker init requires --url <https://your-domain> (or pass --local-eval for localhost evaluation).',
      );
    }
    const parsed = new URL(authUrl);
    if (parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1') {
      throw new Error(
        `Production Docker init cannot use localhost URL "${authUrl}" without --local-eval.`,
      );
    }
  }

  const authSecret =
    existing.BETTER_AUTH_SECRET && existing.BETTER_AUTH_SECRET.length >= 32
      ? existing.BETTER_AUTH_SECRET
      : crypto.randomBytes(32).toString('hex');
  const bootstrapToken =
    existing.BOOTSTRAP_TOKEN && existing.BOOTSTRAP_TOKEN.length >= 16
      ? existing.BOOTSTRAP_TOKEN
      : crypto.randomBytes(16).toString('hex');
  const postgresPassword =
    existing.POSTGRES_PASSWORD && existing.POSTGRES_PASSWORD !== 'burrowpassword'
      ? existing.POSTGRES_PASSWORD
      : crypto.randomBytes(24).toString('hex');

  const lines = [
    '# Generated by scripts/docker-init.mjs',
    `NODE_ENV=production`,
    `PORT=${normalizedPort}`,
    `BIND_HOST=${bindHost}`,
    `ALLOW_LOCAL_DOCKER_EVAL=${localEval ? 'true' : 'false'}`,
    `BETTER_AUTH_URL=${authUrl}`,
    `BETTER_AUTH_SECRET=${authSecret}`,
    `BOOTSTRAP_TOKEN=${bootstrapToken}`,
    `POSTGRES_USER=burrow`,
    `POSTGRES_PASSWORD=${postgresPassword}`,
    `POSTGRES_DB=burrow`,
    `DATABASE_URL=postgres://burrow:${postgresPassword}@postgres:5432/burrow`,
  ];

  return {
    content: `${lines.join('\n')}\n`,
    bootstrapToken,
    authUrl,
    bindHost,
    localEval,
  };
}

function parseArgs(argv) {
  let localEval = false;
  let force = false;
  let url = '';
  let bindHost = '127.0.0.1';
  let port = 3005;

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--local-eval') localEval = true;
    else if (arg === '--force') force = true;
    else if (arg === '--url' && argv[i + 1]) url = argv[++i];
    else if (arg.startsWith('--url=')) url = arg.slice(6);
    else if (arg === '--bind' && argv[i + 1]) bindHost = argv[++i];
    else if (arg.startsWith('--bind=')) bindHost = arg.slice(7);
    else if (arg === '--port' && argv[i + 1]) port = Number(argv[++i]);
    else if (arg.startsWith('--port=')) port = Number(arg.slice(7));
    else if (arg === '--help' || arg === '-h') {
      console.log(
        'Usage:\n' +
          '  node scripts/docker-init.mjs --local-eval\n' +
          '  node scripts/docker-init.mjs --url https://notes.example.com [--bind 127.0.0.1] [--force]\n',
      );
      process.exit(0);
    } else {
      throw new Error(`Unknown flag: ${arg}`);
    }
  }
  return { localEval, force, url, bindHost, port };
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()
) {
  const opts = parseArgs(process.argv.slice(2));
  const envPath = path.join(root, '.env');
  if (fs.existsSync(envPath) && !opts.force) {
    console.error(`Refusing to overwrite existing ${envPath}. Pass --force to regenerate.`);
    process.exit(1);
  }
  const result = buildDockerEnvContent(opts);
  fs.writeFileSync(envPath, result.content, { encoding: 'utf8', mode: 0o600 });
  console.log('\n======================================================');
  console.log('✅ Docker .env configuration created successfully!');
  console.log(`  Mode:            ${result.localEval ? 'Local evaluation (loopback only)' : 'Production'}`);
  console.log(`  BETTER_AUTH_URL: ${result.authUrl}`);
  console.log(`  Bind Address:    ${result.bindHost}:${opts.port}`);
  console.log(`  BOOTSTRAP_TOKEN: ${result.bootstrapToken}`);
  console.log('  Note: BOOTSTRAP_TOKEN is NOT printed in production container logs.');
  console.log('  Next: docker compose up -d --build');
  console.log('======================================================\n');
}
